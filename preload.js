const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('aether', {
  minimize:  () => ipcRenderer.send('win:minimize'),
  close:     () => ipcRenderer.send('win:close'),
  maximize:  () => ipcRenderer.send('win:maximize'),
  navigate:  url => ipcRenderer.send('nav:go', url),
  back:      () => ipcRenderer.send('nav:back'),
  reload:    () => ipcRenderer.send('nav:reload'),
  home:      () => ipcRenderer.send('nav:home'),
  newTab:    () => ipcRenderer.send('tab:new'),
  ghostTab:  () => ipcRenderer.send('tab:ghost'),
  switchTab: id  => ipcRenderer.send('tab:switch', id),
  closeTab:  id  => ipcRenderer.send('tab:close', id),
  purge:     () => ipcRenderer.send('cmd:purge'),
  panic:     () => ipcRenderer.send('cmd:panic'),
  read:      () => ipcRenderer.send('cmd:read'),
  trad:      () => ipcRenderer.send('cmd:translate'),
  guestDev:  () => ipcRenderer.send('cmd:guestdev'),
  shotTake:  () => ipcRenderer.invoke('shot:take'),
  shotSave:  d  => ipcRenderer.send('shot:save', d),
  findStart: t  => ipcRenderer.send('find:start', t),
  findNext:  () => ipcRenderer.send('find:next'),
  findStop:  () => ipcRenderer.send('find:stop'),
  overlay:   on => ipcRenderer.send('ui:overlay', on),
  zoomSet:   pct => ipcRenderer.send('zoom:set', pct),
  setSetting: (key, value) => ipcRenderer.send('set:change', key, value),
  ready:     () => ipcRenderer.send('ui:ready'),
  getBookmarks:   () => ipcRenderer.invoke('bookmarks:get'),
  addBookmark:    bm => ipcRenderer.send('bookmarks:add', bm),
  removeBookmark: url => ipcRenderer.send('bookmarks:remove', url),
  vaultUnlock: m => ipcRenderer.invoke('vault:unlock', m),
  vaultList:   () => ipcRenderer.invoke('vault:list'),
  vaultAdd:    e => ipcRenderer.invoke('vault:add', e),
  vaultUpdate: (i, e) => ipcRenderer.invoke('vault:update', i, e),
  vaultRemove: i => ipcRenderer.invoke('vault:remove', i),
  vaultLock:   () => ipcRenderer.send('vault:lock'),
  vaultSaveAccept:  () => ipcRenderer.send('vault:save-accept'),
  vaultSaveDecline: () => ipcRenderer.send('vault:save-decline'),
  vaultFill:   () => ipcRenderer.send('vault:fill'),
  onStatus:    cb => ipcRenderer.on('nav:status',   (_e, txt, cls) => cb(txt, cls)),
  onUrl:       cb => ipcRenderer.on('nav:url',      (_e, url) => cb(url)),
  onHomeShow:  cb => ipcRenderer.on('nav:home-show', () => cb()),
  onHomeHide:  cb => ipcRenderer.on('nav:home-hide', () => cb()),
  onTabs:      cb => ipcRenderer.on('tabs:update',  (_e, list) => cb(list)),
  onSettings:  cb => ipcRenderer.on('set:state',    (_e, s) => cb(s)),
  onBookmarks: cb => ipcRenderer.on('bookmarks:update', (_e, list) => cb(list)),
  onMaximize:  cb => ipcRenderer.on('win:max',      (_e, v) => cb(v)),
  onZoom:      cb => ipcRenderer.on('zoom:state',   (_e, p) => cb(p)),
  onFocusUrl:  cb => ipcRenderer.on('ui:focus-url', () => cb()),
  onPalette:   cb => ipcRenderer.on('ui:palette',   () => cb()),
  onFind:      cb => ipcRenderer.on('ui:find',      () => cb()),
  onPanic:     cb => ipcRenderer.on('ui:panic',     () => cb()),
  onPurged:    cb => ipcRenderer.on('aether:purged', (_e, n) => cb(n)),
  onDl:        cb => ipcRenderer.on('dl:state',     (_e, d) => cb(d)),
  onVaultState:      cb => ipcRenderer.on('vault:state', (_e, s) => cb(s)),
  onVaultSavePrompt: cb => ipcRenderer.on('vault:prompt-save', (_e, d) => cb(d)),
  onVaultFillPrompt: cb => ipcRenderer.on('vault:prompt-fill', (_e, d) => cb(d)),
  onBlocked:   cb => ipcRenderer.on('aether:blocked', (_e, url) => cb(url)),
  onStats:     cb => ipcRenderer.on('aether:stats',   (_e, n) => cb(n))
});